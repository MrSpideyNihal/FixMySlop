import re
from collections import defaultdict
from pathlib import Path
from typing import Optional

from fixmyslop.core.issue import Issue
from fixmyslop.core.slop.config import SlopConfig, load_config
from fixmyslop.core.slop.rule import RULES, FileContext, Hit, Rule, KIND_MARKUP, KIND_STYLE, KIND_DOC, TEST_PATH_RE
from fixmyslop.core.slop import (  # noqa: F401
    rules_ui, rules_code, rules_security, rules_deps, rules_backend, rules_docs,
)
from fixmyslop.core.slop.rules_deps import DependencyIndex
from fixmyslop.core.slop.theme import ThemeIndex
from fixmyslop.macros import (
    SEVERITY_CRITICAL, SEVERITY_HIGH, SEVERITY_MEDIUM, SEVERITY_LOW, SEVERITY_INFO,
    SEVERITY_RANK, CATEGORY_UI_SLOP, CATEGORY_AI_SMELL, SLOP_TOOL,
    MAX_HITS_PER_RULE_PER_FILE, IGNORE_MARKER, IGNORE_FILE_MARKER,
)
from fixmyslop.utils.git_utils import git_root, tracked_files
from fixmyslop.utils.logger import get_logger

logger = get_logger(__name__)

# ─── Project-level rule metadata (checked in finalize) ──────────────────────
RULES["slop/committed-artifacts"] = Rule(
    id="slop/committed-artifacts", title="Generated artifacts are tracked",
    severity=SEVERITY_LOW, category=CATEGORY_AI_SMELL, kinds=frozenset(),
    why="Generated, local, or platform-specific artifacts are tracked by Git and can add noise or "
        "unnecessary size to the repository.",
    fix="Run `git rm -r --cached <path>` for the affected path(s), then add matching patterns to "
        "`.gitignore`.",
)

_COMMITTED_ARTIFACT_KINDS = (
    ("under node_modules/", lambda parts, name: "node_modules" in parts),
    ("under .venv/ or venv/", lambda parts, name: bool({".venv", "venv"} & set(parts))),
    ("under __pycache__/ or matching *.pyc",
     lambda parts, name: "__pycache__" in parts or name.endswith(".pyc")),
    ("under .next/", lambda parts, name: bool({".next"} & set(parts))),
    ("named .DS_Store", lambda parts, name: name == ".DS_Store"),
    ("matching *.log", lambda parts, name: name.endswith(".log")
     and not TEST_PATH_RE.search("/".join((*parts, name)))),
)
RULES["ui/rainbow-palette"] = Rule(
    id="ui/rainbow-palette", title="Too many accent color families", severity=SEVERITY_MEDIUM,
    category=CATEGORY_UI_SLOP, kinds=frozenset({KIND_MARKUP}),
    why="Each generated component picked its own accent (blue here, emerald there, a purple hero…). "
        "A coherent product uses one accent plus neutrals and a few semantic colors.",
    fix="Choose one primary accent and map every other decorative color to it or to neutrals. Keep "
        "red/amber/green only for semantic states (error/warning/success).",
)
RULES["ui/palette-sprawl"] = Rule(
    id="ui/palette-sprawl", title="Palette sprawl", severity=SEVERITY_MEDIUM,
    category=CATEGORY_UI_SLOP, kinds=frozenset({KIND_STYLE, KIND_MARKUP}),
    why="Dozens of distinct hardcoded hex colors means there is no design system — every screen "
        "drifts a little.",
    fix="Define color tokens (CSS variables or tailwind theme) for the handful of colors you need and "
        "replace raw hex values with them.",
)

RULES["ui/off-scale-values"] = Rule(
    id="ui/off-scale-values", title="Spacing/type off the scale", severity=SEVERITY_LOW,
    category=CATEGORY_UI_SLOP, kinds=frozenset({KIND_MARKUP}),
    why="Dozens of one-off sizes (text-[11px], w-[347px], tracking-[0.3em]…) mean every component was "
        "eyeballed separately — the layout feels slightly off and nothing lines up.",
    fix="Snap arbitrary values to the Tailwind/theme scale (text-xs, w-80, tracking-widest). Keep an "
        "arbitrary value only where a real constraint requires it, and add it to the theme if it repeats.",
)

RAINBOW_FAMILY_LIMIT = 6
OFF_SCALE_LIMIT = 20
_HAIRLINES = {"0.5px", "1px", "2px", "3px"}
_ALWAYS_ON_VENDORED = ("sec/leaked-key", "sec/hardcoded-credential", "sec/public-env-secret", "deps/")
_GENERATED_NAME = re.compile(r"\.(?:gen|generated)\.\w+$|_pb2(?:_grpc)?\.py$|\.pb\.go$|(?:^|/)__generated__/")
_GENERATED_HEADER = re.compile(r"@generated|auto-?generated|automatically generated|do not edit|code generated by",
                               re.IGNORECASE)
PALETTE_HEX_LIMIT = 24
SEVERITY_WEIGHTS = {
    SEVERITY_CRITICAL: 10.0, SEVERITY_HIGH: 5.0, SEVERITY_MEDIUM: 2.0,
    SEVERITY_LOW: 0.75, SEVERITY_INFO: 0.1,
}
_TOKEN_DEFINITION = re.compile(r"--[\w-]+\s*:[^;{}]*")
_IGNORE_RE = re.compile(re.escape(IGNORE_MARKER) + r"(?:\[([^\]]*)\])?")


class SlopEngine:
    """Deterministic, offline slop detector."""

    def __init__(self, root: Path, config: Optional[SlopConfig] = None, online: bool = False):
        """Prepare rules and the project dependency index."""
        self.root = Path(root).resolve()
        if self.root.is_file():
            self.root = self.root.parent
        self.config = config or load_config(self.root)
        self.online = online
        self.rules = [r for r in RULES.values() if r.check is not None and self.config.rule_enabled(r.id)]
        self._deps: Optional[DependencyIndex] = None
        self._theme: Optional[ThemeIndex] = None
        self._off_scale: dict[str, tuple[str, int, int]] = {}
        self._pending: dict[str, list[Issue]] = defaultdict(list)
        self._occurrences: dict[str, int] = defaultdict(int)   # raw hits, before per-file aggregation
        self._records: dict[str, dict[str, list]] = defaultdict(lambda: defaultdict(list))
        self._color_families: dict[str, tuple[str, int]] = {}
        self._hex_by_file: dict[str, set[str]] = defaultdict(set)
        self.lines_scanned = 0
        self.files_scanned = 0
        self.whole_project = True

    @property
    def deps(self) -> DependencyIndex:
        """Lazily build the dependency index (walks the tree once)."""
        if self._deps is None:
            self._deps = DependencyIndex(self.root, online=self.online)
        return self._deps

    @property
    def theme(self) -> ThemeIndex:
        """Lazily index the project's design tokens (CSS variables, fonts, icons)."""
        if self._theme is None:
            self._theme = ThemeIndex.build(self.root)
        return self._theme

    def record(self, rule_id: str, key: str, item: tuple):
        """Project-wide observations for cross-file rules (e.g. duplicated functions)."""
        self._records[rule_id][key].append(item)

    def is_vendored(self, rel: str) -> bool:
        """shadcn/ui's generated components/ui/* is library code, not the author's slop."""
        return "/components/ui/" in "/" + rel and self.theme.shadcn

    def relpath(self, path: Path) -> str:
        """Project-relative POSIX path (falls back to the absolute path)."""
        try:
            return Path(path).resolve().relative_to(self.root).as_posix()
        except ValueError:
            return Path(path).as_posix()

    # ── per-file ────────────────────────────────────────────────────────────
    def check_file(self, path: Path, content: str) -> list[Issue]:
        """Run every applicable rule on one file and return its issues."""
        path = Path(path)
        rel = self.relpath(path)
        if self.config.is_excluded(rel):
            return []
        head = "\n".join(content.splitlines()[:10])
        if IGNORE_FILE_MARKER in head:
            return []
        ctx = FileContext(path, rel, content, project=self)
        self.files_scanned += 1
        if KIND_DOC not in ctx.kinds:      # the score is slop per line of code; prose would dilute it
            self.lines_scanned += sum(1 for line in ctx.lines if line.strip())

        vendored = self.is_vendored(rel) or bool(_GENERATED_NAME.search(rel)) \
            or bool(_GENERATED_HEADER.search("\n".join(content.splitlines()[:5])))
        issues: list[Issue] = []
        for rule in self.rules:
            if not rule.applies_to(ctx):
                continue
            if vendored and not rule.id.startswith(_ALWAYS_ON_VENDORED):
                continue
            try:
                hits = [h for h in rule.check(ctx) if not self._suppressed(ctx, h.line, rule.id)]
            except Exception as e:
                logger.warning("Rule %s crashed on %s: %s", rule.id, rel, e)
                continue
            self._occurrences[rule.id] += len(hits)
            if rule.aggregate_per_file and len(hits) > 1:
                lines = ", ".join(str(h.line) for h in hits[:12]) + (" …" if len(hits) > 12 else "")
                hits = [Hit(hits[0].line, hits[0].evidence, f"{len(hits)} occurrences in this file (lines {lines})")]
            for hit in hits[:MAX_HITS_PER_RULE_PER_FILE]:
                issue = self._to_issue(rule, ctx, hit)
                if rule.project_threshold or rule.once_per_project:
                    self._pending[rule.id].append(issue)
                else:
                    issues.append(issue)

        if not ctx.is_test and not vendored and (ctx.has(KIND_MARKUP) or ctx.has(KIND_STYLE)):
            self._observe_palette(ctx)
        return issues

    def _suppressed(self, ctx: FileContext, line: int, rule_id: str) -> bool:
        """Honor `fixmyslop-ignore` / `fixmyslop-ignore[rule,...]` on the line or the line above."""
        for text in (ctx.line_text(line), ctx.line_text(line - 1)):
            match = _IGNORE_RE.search(text)
            if not match:
                continue
            if not match.group(1):
                return True
            wanted = [r.strip() for r in match.group(1).split(",")]
            if any(rule_id == w or (w.endswith("/") and rule_id.startswith(w))
                   or rule_id.split("/")[0] == w for w in wanted):
                return True
        return False

    def _to_issue(self, rule: Rule, ctx: FileContext, hit: Hit) -> Issue:
        """Convert a rule hit into the shared Issue model."""
        severity = self.config.severity.get(rule.id) or hit.severity or rule.severity
        description = rule.why
        if hit.message:
            description = f"{hit.message}. {rule.why}" if len(hit.message) > 3 else rule.why
        return Issue(
            file_path=str(ctx.path),
            line_start=hit.line,
            line_end=hit.end_line or hit.line,
            severity=severity,
            category=rule.category,
            rule_id=rule.id,
            title=rule.title,
            description=description,
            evidence=hit.evidence[:300],
            suggested_fix=rule.fix,
            source_tool=SLOP_TOOL,
        )

    # ── project-level ───────────────────────────────────────────────────────
    def _observe_palette(self, ctx: FileContext):
        """Track Tailwind color families and raw hex colors for palette rules."""
        for n, line in enumerate(ctx.lines, 1):
            if ctx.is_comment(n):
                continue
            for family in rules_ui.TW_COLOR_FAMILY.findall(line):
                self._color_families.setdefault(family, (str(ctx.path), n))
            # Colors defined as design tokens (--name: #hex) ARE the design system, not sprawl.
            raw = _TOKEN_DEFINITION.sub("", line)
            for hex_color in rules_ui.HEX_COLOR.findall(raw):
                self._hex_by_file[str(ctx.path)].add(_normalize_hex(hex_color))
            if ctx.has(KIND_MARKUP):
                for match in rules_ui.ARBITRARY_SIZE.finditer(line):
                    value = match.group(0).lstrip("-")
                    if match.group(1) in _HAIRLINES:
                        continue
                    path, first_line, count = self._off_scale.get(value, (str(ctx.path), n, 0))
                    self._off_scale[value] = (path, first_line, count + 1)

    def finalize(self) -> list[Issue]:
        """Emit threshold-gated rule hits and project-level palette findings."""
        issues: list[Issue] = []
        for rule_id, pending in self._pending.items():
            rule = RULES[rule_id]
            if rule.once_per_project:
                first = pending[0]
                if len(pending) > 1:
                    first.description = f"Seen in {len(pending)} places. {first.description}"
                issues.append(first)
            elif self._occurrences[rule_id] >= rule.project_threshold:
                issues.extend(pending)
        self._pending.clear()
        self._occurrences.clear()
        issues.extend(self._duplicate_issues())

        if self.config.rule_enabled("ui/rainbow-palette") and len(self._color_families) > RAINBOW_FAMILY_LIMIT:
            path, line = min(self._color_families.values())
            families = ", ".join(sorted(self._color_families))
            issues.append(self._project_issue(
                "ui/rainbow-palette", path, line,
                f"{len(self._color_families)} accent color families in use: {families}",
            ))
        if self.config.rule_enabled("ui/off-scale-values") and len(self._off_scale) >= OFF_SCALE_LIMIT:
            by_file: dict[str, int] = defaultdict(int)
            for path, _, count in self._off_scale.values():
                by_file[path] += count
            worst = max(by_file, key=by_file.get)
            first = min(line for path, line, _ in self._off_scale.values() if path == worst)
            top = sorted(self._off_scale.items(), key=lambda kv: -kv[1][2])[:8]
            issues.append(self._project_issue(
                "ui/off-scale-values", worst, first,
                f"{len(self._off_scale)} distinct off-scale values, most used: "
                + ", ".join(f"{value} ×{meta[2]}" for value, meta in top),
            ))
        all_hex = set().union(*self._hex_by_file.values()) if self._hex_by_file else set()
        if self.config.rule_enabled("ui/palette-sprawl") and len(all_hex) > PALETTE_HEX_LIMIT:
            worst = max(self._hex_by_file, key=lambda p: len(self._hex_by_file[p]))
            issues.append(self._project_issue(
                "ui/palette-sprawl", worst, 1,
                f"{len(all_hex)} distinct hardcoded colors across the project "
                f"({len(self._hex_by_file[worst])} in this file)",
            ))
        issues.extend(self._committed_artifact_issues())
        return issues

    def _committed_artifact_issues(self) -> list[Issue]:
        """Report tracked generated and local artifacts, grouped by kind."""
        if not self.whole_project:
            return []
        rule_id = "slop/committed-artifacts"
        if not self.config.rule_enabled(rule_id):
            return []
        root = git_root(self.root)
        if root is None:
            return []
        files = tracked_files(root)
        if files is None:
            return []

        issues = []
        for kind, matches in _COMMITTED_ARTIFACT_KINDS:
            matched = [
                path for path in files
                if matches(path.split("/")[:-1], path.rsplit("/", 1)[-1])
            ]
            if not matched:
                continue
            count = len(matched)
            noun = "file" if count == 1 else "files"
            verb = "is" if count == 1 else "are"
            issues.append(self._project_issue(
                rule_id, str(root / matched[0]), 1,
                f"{count} {noun} {kind} {verb} committed",
            ))
        return issues

    def _duplicate_issues(self) -> list[Issue]:
        """One issue per extra copy of a function body seen in 2+ places."""
        result = []
        if not self.config.rule_enabled("slop/duplicate-function"):
            return result
        for items in self._records.pop("slop/duplicate-function", {}).values():
            if len(items) < 2:
                continue
            first_path, first_line, first_name, _ = items[0]
            for path, line, name, evidence in items[1:]:
                issue = self._project_issue(
                    "slop/duplicate-function", path, line,
                    f"`{name}` duplicates `{first_name}` in {self.relpath(Path(first_path))}:{first_line}")
                issue.evidence = evidence
                result.append(issue)
        return result

    def _project_issue(self, rule_id: str, path: str, line: int, message: str) -> Issue:
        """Build an Issue for a project-level rule."""
        rule = RULES[rule_id]
        hit = Hit(line, "", message)
        ctx_like = type("Ctx", (), {"path": Path(path)})()
        return self._to_issue(rule, ctx_like, hit)


def _normalize_hex(value: str) -> str:
    """#abc → #aabbcc, lowercase."""
    value = value.lower().lstrip("#")
    if len(value) == 3:
        value = "".join(c * 2 for c in value)
    return "#" + value


# ─── Scoring ────────────────────────────────────────────────────────────────

def slop_score(issues: list[Issue], lines_scanned: int) -> float:
    """0 (clean) → 100 (pure slop), from severity-weighted issue density per 1k lines."""
    if not issues:
        return 0.0
    weight = sum(SEVERITY_WEIGHTS.get(i.severity, 1.0) for i in issues)
    density = weight / max(lines_scanned, 200) * 1000
    return round(100 * (1 - math.exp(-density / 40)), 1)


def grade(score: float) -> str:
    """Letter grade for a slop score."""
    if score < 10:
        return "A"
    if score < 25:
        return "B"
    if score < 45:
        return "C"
    if score < 65:
        return "D"
    return "F"


def at_or_above(issues: list[Issue], threshold: str) -> list[Issue]:
    """Issues whose severity is at or above a threshold name (e.g. 'high')."""
    limit = SEVERITY_RANK.get(threshold.upper())
    if limit is None:
        return []
    return [i for i in issues if SEVERITY_RANK.get(i.severity, 99) <= limit]
